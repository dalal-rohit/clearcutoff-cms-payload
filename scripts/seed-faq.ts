// Payload's Postgres adapter fully replaces an array field's rows on every
// `updateGlobal` write. Writing locale='en' then locale='hi' in two separate
// calls means the second call's row-recreate silently drops the first
// locale's data. Instead, merge both locales' text into single {en, hi}
// objects per localized field and write everything in one `locale: 'all'`
// call, which is the local-API-documented way to seed multiple locales.
function mergeLocales(en: Category[], hi: Category[]) {
  return en.map((c, i) => ({
    key: c.key,
    label: { en: c.label, hi: hi[i].label },
    questions: c.questions.map((q, j) => ({
      question: { en: q.question, hi: hi[i].questions[j].question },
      answer: { en: q.answer, hi: hi[i].questions[j].answer },
    })),
  }))
}

async function run() {
  const payload = await getPayload({ config })

  await payload.updateGlobal({
    slug: 'faq',
    locale: 'all',
    data: { categories: mergeLocales(EN, HI) },
  })

  payload.logger.info('FAQ global seeded (en + hi).')
  process.exit(0)
}

run().catch((err) => {
  console.error('FAQ seed failed:', err)
  process.exit(1)
})
